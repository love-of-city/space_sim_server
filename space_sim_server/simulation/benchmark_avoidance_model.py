"""A native passive sphere is an explicit synthetic debris asset, not a satellite."""
import hashlib
import json
import xml.etree.ElementTree as ET

from simulation.benchmark_orbit_model import prepare_orbit_model


def prepare_avoidance_model(repository, destination, task):
    model, files, manifest = prepare_orbit_model(repository, destination, force_limit_n=task.safety.maximum_force_n)
    root = ET.parse(model).getroot()
    e = task.encounter
    inertia = 2*e.mass_kg*e.radius_m**2/5
    body = ET.SubElement(root.find('worldbody'), 'body', name='benchmark_debris', pos='0 0 1500')
    ET.SubElement(body, 'freejoint', name='benchmark_debris_free')
    ET.SubElement(body, 'inertial', pos='0 0 0', mass=str(e.mass_kg), diaginertia=' '.join([str(inertia)]*3))
    ET.SubElement(body, 'geom', name='benchmark_debris_sphere', type='sphere', size=str(e.radius_m),
                  rgba='.35 .35 .35 1', contype='1', conaffinity='1')
    ET.SubElement(body, 'site', name='benchmark_debris_center', pos='0 0 0', size='.01')
    root.set('model', 'SpaceSim_single_SARM_and_passive_debris')
    ET.indent(root)
    ET.ElementTree(root).write(model, encoding='utf-8', xml_declaration=True)
    manifest['bodies']['benchmark_debris'] = dict(mass_kg=e.mass_kg, center_body_m=[0.,0.,0.],
        inertia_kg_m2=[inertia]*3, radius_m=e.radius_m, object_type=e.object_type,
        source='analytic solid sphere generated by this repository; no third-party asset',
        geometry_model='synthetic homogeneous rigid body, not a measured fragment', actuators=[])
    manifest.update(generated_sha256=hashlib.sha256(model.read_bytes()).hexdigest(),
        geometry_count=len(root.findall('.//geom')), body_count=len(root.findall('.//body')),
        spacecraft_count=1, debris_count=1,
        derivation='single original stowed SARM plus one independent unactuated analytic debris body',
        scope='single-spacecraft conjunction avoidance; no cooperative target telemetry or contact success')
    (destination/'model_manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    return model, files, manifest
